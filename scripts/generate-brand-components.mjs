// Converts the branding SVGs into React components whose accent colours come
// from CSS variables instead of baked-in hex.
//
// Why generate rather than hand-write: the path data is thousands of characters
// of designer output. Re-running this after new art lands is safer than editing
// JSX by hand, and it keeps the colour mapping in one reviewable place.
//
// Two things this has to get right:
//
//   1. Gradient ids must be unique per rendered instance. The nav and the login
//      page can both mount a lockup; duplicate ids in one document make the
//      second instance reference the first one's gradient. Every id is prefixed
//      with React's useId().
//
//   2. The marks use multi-stop gradients, so the accent cannot just be
//      substituted flat. Each stop maps to a token or a color-mix() of two
//      tokens, preserving the light-to-dark ramp for any accent.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const ACCENT = "var(--color-league-accent)";
const DEEP = "var(--color-league-accent-border)";

// Source stop -> token expression. The four cyans are the ramp from the
// brightest highlight down to the deepest shadow.
const COLOR_MAP = {
  "#22d3ee": ACCENT,
  "#16d0ed": `color-mix(in srgb, ${ACCENT} 88%, ${DEEP})`,
  "#0e99b3": `color-mix(in srgb, ${ACCENT} 32%, ${DEEP})`,
  "#0c839c": DEEP,
};

const ATTR_MAP = {
  "stop-color": "stopColor",
  "stop-opacity": "stopOpacity",
  "stroke-width": "strokeWidth",
  "stroke-linecap": "strokeLinecap",
  "stroke-linejoin": "strokeLinejoin",
  "stroke-miterlimit": "strokeMiterlimit",
  "clip-path": "clipPath",
  "clip-rule": "clipRule",
  "fill-rule": "fillRule",
  "fill-opacity": "fillOpacity",
  "gradientUnits": "gradientUnits",
  "data-name": "dataName",
  "xmlns:xlink": "xmlnsXlink",
  "xlink:href": "xlinkHref",
};

function convert(svg, componentName) {
  let s = svg
    .replace(/<\?xml[^>]*\?>\s*/g, "")
    .replace(/<!--[\s\S]*?-->/g, "")
    .trim();

  // Collect gradient / clip ids so they can be namespaced per instance.
  const ids = [...s.matchAll(/\sid="([^"]+)"/g)].map((m) => m[1]);

  for (const id of ids) {
    // Escape regex metacharacters in ids like "linear-gradient-2".
    const esc = id.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    s = s.replace(new RegExp(`\\sid="${esc}"`, "g"), ` id={\`\${uid}-${id}\`}`);
    s = s.replace(new RegExp(`url\\(#${esc}\\)`, "g"), `url(#\${uid}-${id})`);
    // Illustrator emits gradients that inherit their stops via
    // xlink:href="#first-gradient". Namespacing the id without rewriting these
    // leaves them pointing at an id that no longer exists, so the gradient has
    // no stops and every shape using it paints nothing — the shapes do not
    // error, they just silently vanish. Emitted as SVG2 `href`, which every
    // target browser supports and React passes through without the xlink
    // deprecation warning.
    s = s.replace(
      new RegExp(`\\s(?:xlink:href|href)="#${esc}"`, "g"),
      ` href={\`#\${uid}-${id}\`}`
    );
  }

  // url(...) now contains a template expression, so those attributes must
  // become JSX expressions rather than plain strings.
  s = s.replace(/(fill|stroke|clip-path)="(url\(#\$\{uid\}[^"]*\))"/g, (_m, attr, val) => {
    const jsxAttr = ATTR_MAP[attr] ?? attr;
    return `${jsxAttr}={\`${val}\`}`;
  });

  // Accent colours -> token expressions.
  for (const [hex, token] of Object.entries(COLOR_MAP)) {
    s = s.replace(new RegExp(hex, "gi"), token);
  }

  // Kebab-case attributes -> JSX names.
  for (const [from, to] of Object.entries(ATTR_MAP)) {
    s = s.replace(new RegExp(`\\s${from}=`, "g"), ` ${to}=`);
  }

  // These carry no meaning once inlined and dataName is not a valid DOM prop.
  s = s.replace(/\sdataName="[^"]*"/g, "");
  s = s.replace(/\sxmlnsXlink="[^"]*"/g, "");

  // Let the caller size and label it.
  s = s.replace(
    /^<svg\s/,
    '<svg className={className} role="img" aria-label={title} '
  );

  return `// GENERATED by scripts/generate-brand-components.mjs — do not edit by hand.
// Accent colours reference --color-league-accent, which falls back to the
// product accent, so this renders correctly inside and outside a league.
import { useId } from "react";

interface Props {
  className?: string;
  title?: string;
}

export default function ${componentName}({ className = "h-24 w-auto", title = "DraftHQ" }: Props) {
  const uid = useId().replace(/:/g, "");
  return (
    ${s.split("\n").join("\n    ")}
  );
}
`;
}

mkdirSync("src/components/brand", { recursive: true });

const FILES = [
  ["mark", "DraftHQMark"],
  ["lockup", "DraftHQLockup"],
  ["wordmark", "DraftHQWordmark"],
];

for (const [file, name] of FILES) {
  const svg = readFileSync(`public/branding/${file}.svg`, "utf8");
  writeFileSync(`src/components/brand/${name}.tsx`, convert(svg, name));
  console.log("generated", name);
}
